import { chromium } from "@playwright/test";
const out = process.argv[2];
const b = await chromium.launch({ args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader"] });
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
p.on("pageerror", (e) => console.log("PAGEERR", e.message));
p.on("console", (m) => (m.type() === "error") && console.log("CONSOLE", m.text().slice(0, 220)));
await p.goto("http://localhost:3000/interests", { waitUntil: "networkidle" });
await p.waitForTimeout(2000);
await p.getByRole("button", { name: /^Play Watches/ }).click();
await p.waitForTimeout(6000);
await p.screenshot({ path: `${out}/dj-silver.png` });
await p.getByRole("button", { name: "Blue dial" }).click(); await p.waitForTimeout(1500);
await p.screenshot({ path: `${out}/dj-blue.png` });
await p.locator('[role=dialog] input[type=range]').fill("100"); await p.waitForTimeout(3000);
await p.screenshot({ path: `${out}/dj-exploded.png` });
await p.keyboard.press("Escape"); await p.waitForTimeout(800);
await p.getByRole("button", { name: /^Play Keyboards/ }).click();
await p.waitForTimeout(6000);
await p.locator('[role=dialog] input[type=range]').fill("50"); await p.waitForTimeout(2500);
await p.screenshot({ path: `${out}/kb-half.png` });
await p.locator('[role=dialog] input[type=range]').fill("100"); await p.waitForTimeout(2500);
await p.screenshot({ path: `${out}/kb-full.png` });
await b.close();
